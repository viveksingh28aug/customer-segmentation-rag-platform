"""Grounded analyst chat page backed by the FastAPI RAG endpoint."""

from __future__ import annotations

import streamlit as st

from frontend.path_setup import ensure_project_root

ensure_project_root()

from frontend.api_client import ChatStreamError, get_status, post_chat_stream
from frontend.ui import apply_dashboard_style, data_mode_label, page_header

st.set_page_config(page_title="Analyst Chat", page_icon="💬", layout="wide")
apply_dashboard_style()
page_header(
    "Grounded AI analysis",
    "Analyst Chat",
    "Ask questions about the served segment profiles, product affinities, and campaign results. "
    "Answers are generated by Groq and checked against retrieved project context.",
)

if "chat_thread_id" not in st.session_state:
    st.session_state.chat_thread_id = None
if "chat_messages" not in st.session_state:
    st.session_state.chat_messages = []
if "analyst_question" not in st.session_state:
    st.session_state.analyst_question = ""


def choose_question(question: str) -> None:
    """Copy a suggested question into the analyst input."""
    st.session_state.analyst_question = question


def reset_conversation() -> None:
    """Clear visible history and server-side conversation identity."""
    st.session_state.chat_thread_id = None
    st.session_state.chat_messages = []
    st.session_state.analyst_question = ""


try:
    status = get_status()
except RuntimeError as exc:
    st.error(str(exc))
    st.stop()

status_cols = st.columns([3, 1])
with status_cols[0]:
    st.caption(
        f'Data source: **{data_mode_label(status["data_mode"])}** · '
        "Answers use only retrieved local analytical artifacts."
    )
with status_cols[1]:
    st.button("Reset conversation", on_click=reset_conversation, width="stretch")

if not status["chat_configured"]:
    st.warning(
        "AI chat is not configured. Add a valid `GROQ_API_KEY` to `.env`, restart the API, "
        "and refresh this page. The Overview and Recommendations pages remain fully usable."
    )
    st.caption("No offline text is presented as a Groq-generated answer.")

st.markdown("#### Suggested questions")
examples = [
    "Who are our high-value promo-sensitive shoppers?",
    "What products should we target to segment 2?",
    "Which segment shows the strongest campaign response?",
    "What evidence supports the top recommendation for segment 2?",
]
example_cols = st.columns(2)
for index, example in enumerate(examples):
    example_cols[index % 2].button(
        example,
        key=f"example_{index}",
        on_click=choose_question,
        args=(example,),
        width="stretch",
    )

st.divider()
for message in st.session_state.chat_messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])
        if message["role"] == "assistant":
            sources = message.get("sources", [])
            if sources:
                source_names = ", ".join(
                    f'Segment {source["segment_id"]}: {source["segment_name"]}'
                    for source in sources
                )
                st.caption(f"Retrieved context: {source_names}")
            if message.get("validated") is True:
                st.caption("✓ Numerical claims matched the retrieved context.")
            elif message.get("validated") is False:
                st.caption("⚠ Some numerical claims could not be validated against retrieved context.")

with st.form("analyst_chat_form", clear_on_submit=False):
    st.text_area(
        "Question",
        key="analyst_question",
        placeholder="Ask about a segment, product lift, or campaign response…",
        height=90,
        max_chars=2000,
    )
    submitted = st.form_submit_button(
        "Ask analyst",
        type="primary",
        disabled=not status["chat_configured"],
    )

if submitted:
    question = st.session_state.analyst_question.strip()
    if not question:
        st.warning("Enter a question before submitting.")
    else:
        st.session_state.chat_messages.append({"role": "user", "content": question})
        with st.chat_message("user"):
            st.markdown(question)

        with st.chat_message("assistant"):
            answer_placeholder = st.empty()
            stream_buffer: list[str] = [""]

            def append_token(token: str) -> None:
                stream_buffer[0] += token
                answer_placeholder.markdown(stream_buffer[0] + "▌")

            try:
                with st.spinner("Retrieving evidence and generating analysis…"):
                    result = post_chat_stream(
                        question,
                        thread_id=st.session_state.chat_thread_id,
                        on_token=append_token,
                    )
            except ChatStreamError as exc:
                answer_placeholder.empty()
                if stream_buffer[0]:
                    st.caption("Incomplete response (not saved)")
                    st.markdown(stream_buffer[0])
                st.error(f"Chat could not complete ({exc.code}): {exc.message}")
                st.info(
                    "Retry once. If the error persists, confirm the backend is running, verify "
                    "`GROQ_API_KEY`, and check whether the provider is rate-limiting requests."
                )
            except Exception:
                answer_placeholder.empty()
                st.error("Chat could not complete because of an unexpected local client error.")
                st.info("Check the Streamlit console for diagnostics, then retry.")
            else:
                answer = str(result["answer"]).strip()
                answer_placeholder.markdown(answer)
                st.session_state.chat_thread_id = result.get("thread_id")
                validation = result.get("validation", {})
                sources = result.get("retrieved_segments", [])
                st.session_state.chat_messages.append(
                    {
                        "role": "assistant",
                        "content": answer,
                        "sources": sources,
                        "validated": validation.get("validated"),
                    }
                )
                if sources:
                    source_names = ", ".join(
                        f'Segment {source["segment_id"]}: {source["segment_name"]}'
                        for source in sources
                    )
                    st.caption(f"Retrieved context: {source_names}")
                if validation.get("validated"):
                    st.success("Numerical claims matched the retrieved context.")
                else:
                    st.warning(
                        "Some numerical claims could not be validated. Treat the response as "
                        "an interpretation and verify it against the source tables."
                    )

st.caption(
    "AI-generated analysis can be incomplete. Measured values come from the retrieved segment "
    "cards; qualitative statements are model interpretations."
)
